#!/usr/bin/env node
// Regenerates the POI_REGIONS data in src/rag/poiRegions.ts (between the
// "generated" markers) from built places packs, so sizes, SHA-256 and counts
// in the catalog are always the measured ones.
//
//   node scripts/poi-regions-catalog.mjs poi/sao-paulo.sqlite poi/berlin.sqlite ...
import { readFileSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";

const TARGET = "src/rag/poiRegions.ts";
const regions = process.argv.slice(2).map((file) => {
  const s = JSON.parse(readFileSync(`${file}.json`, "utf8"));
  const db = new DatabaseSync(file, { readOnly: true });
  const m = Object.fromEntries(db.prepare("SELECT key, value FROM meta").all().map((r) => [r.key, r.value]));
  db.close();
  return {
    id: m.id,
    name: { en: m.nameEn, pt: m.namePt },
    sizeBytes: s.sizeBytes,
    sha256: s.sha256,
    sourceUrl: "",
    filename: `poi/${m.id}.sqlite`,
    poiCount: Number(m.poiCount),
    veganCount: s.vegan,
    vegetarianCount: s.vegetarian,
    cities: JSON.parse(m.cities).map((c) => ({ name: c.name, lat: +c.lat.toFixed(4), lon: +c.lon.toFixed(4), pois: c.pois })),
    bbox: JSON.parse(m.bbox),
    timeZones: JSON.parse(m.timeZones),
    osmDate: m.osmDate,
    builtAt: m.builtAt,
  };
});
const body = JSON.stringify(regions, null, 2).replace(/"([a-zA-Z0-9]+)":/g, "$1:");
const src = readFileSync(TARGET, "utf8");
const start = "// <generated by scripts/poi-regions-catalog.mjs>";
const end = "// </generated>";
const a = src.indexOf(start);
const b = src.indexOf(end);
if (a < 0 || b < 0) throw new Error(`markers not found in ${TARGET}`);
writeFileSync(TARGET, `${src.slice(0, a + start.length)}\nexport const POI_REGIONS: PoiRegion[] = ${body};\n${src.slice(b)}`);
console.log(`${regions.length} regions written to ${TARGET}`);
